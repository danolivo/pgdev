/*-------------------------------------------------------------------------
 *
 * numeric_bounded.c
 *	  sum() and avg() over numeric of bounded precision and scale.
 *
 * When the planner can show that every input of sum(numeric) or
 * avg(numeric) has at most NUMERIC_BOUNDED_MAX_PRECISION digits at one fixed
 * scale, numeric_agg_support() replaces the aggregate with
 * bounded_numeric_sum() or bounded_numeric_avg().  These take the scale as a
 * second, constant argument and accumulate every input as an integer
 * mantissa at that scale in an INT128.
 *
 * What this buys is cheaper accumulation and a smaller state.  Per row, an
 * input costs a short Horner loop over its few base-NBASE digits and one
 * INT128 addition, where the general aggregate unpacks it into a NumericVar
 * and adds it digit by digit into the arrays of a NumericSumAccum, with carry
 * propagation and maxScale bookkeeping; that is most of the gain when there
 * are few groups.  Per group, the state is one 64-byte allocation with no
 * digit arrays hanging off it, where the general aggregate keeps a
 * NumericAggState with separately allocated ones; that makes groups cheaper
 * to create and shrinks the per-group footprint of a HashAggregate, which
 * moves its spill point, and adds to the gain when there are many groups.
 * How an input is read off its varlena hardly matters by comparison; see
 * bounded_numeric_unpack() in numeric.c.
 *
 * Everything that needs to know how a numeric is represented is in
 * numeric.c, behind the interface in numeric_bounded.h; this file deals in
 * mantissas only.
 *
 * This module is meant for use by an application that is part of an ERP
 * system, where the queries are generated by the application and a direct
 * call of the bounded aggregates is not possible: they are only ever reached
 * through the planner's substitution of sum() and avg().  The checks made
 * on their arguments below are there for robustness, not because such calls
 * are expected.
 *
 * A typmod is a promise, not a guarantee: a value can arrive from an FDW, or
 * out of a record cast, without honoring the declaration.  Every input is
 * therefore checked against the scale the aggregate was specialized on.  An
 * input that does not fit, like a group that has taken as many inputs as the
 * accumulator can safely hold, makes the state fall back to the general
 * NumericAggState, built from what has been accumulated so far; from then on
 * the group is handled by the general transition, combine and final
 * functions.  So the answer is always the one sum() and avg() give, and the
 * bounded representation is only ever an optimization.  That also covers a
 * mistake in the plan-time derivation in numeric_agg_support().
 *
 * Portions Copyright (c) 1996-2026, PostgreSQL Global Development Group
 *
 * IDENTIFICATION
 *	  src/backend/utils/adt/numeric_bounded.c
 *
 *-------------------------------------------------------------------------
 */
